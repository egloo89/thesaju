const {chromium} = require(process.env.SAJU_PLAYWRIGHT_PATH || 'playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');

(async()=>{
  fs.mkdirSync('tmp/visual',{recursive:true});fs.mkdirSync('output/pdf',{recursive:true});
  const browser = await chromium.launch({headless:true, ...(process.env.SAJU_BROWSER_CHANNEL ? {channel:process.env.SAJU_BROWSER_CHANNEL} : {})});
  const page = await browser.newPage({viewport:{width:1280,height:900},acceptDownloads:true});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(process.env.SAJU_QA_URL || 'http://127.0.0.1:3001',{waitUntil:'networkidle'});
  await page.screenshot({path:'tmp/visual/home-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'윤',exact:true}).click();
  await page.getByRole('button',{name:'윤',exact:true}).getAttribute('aria-pressed').then(v=>assert.equal(v,'true'));
  await page.getByRole('button',{name:'서하',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'tmp/visual/home-mobile.png',fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'mobile horizontal overflow');
  await page.getByRole('button',{name:'내 사주 만나보기',exact:true}).click();
  await page.getByRole('dialog').waitFor();
  await page.screenshot({path:'tmp/visual/checkout-mobile.png'});
  await page.getByRole('button',{name:'먼저 무료로 체험하기'}).click();
  const selects=page.locator('form select');
  await selects.nth(0).selectOption('1989');await selects.nth(1).selectOption('10');await selects.nth(2).selectOption('28');await selects.nth(3).selectOption('10');
  await page.getByRole('button',{name:'사주 분석 시작'}).click();
  await page.locator('.result-overview').waitFor({timeout:30000});
  await page.locator('.web-report').waitFor({timeout:30000});
  await page.screenshot({path:'tmp/visual/result-mobile.png'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'result horizontal overflow');
  const chips=await page.locator('.element-chips strong').allTextContents();assert.deepEqual(chips,['1','1','4','2','0']);
  const request = page.waitForEvent('download',{timeout:180000});
  await page.getByRole('button',{name:/PDF 다운로드/}).click();
  const download=await request;await download.saveAs(path.resolve('output/pdf/redesign-full.pdf'));
  console.log(JSON.stringify({pdfBytes:fs.statSync('output/pdf/redesign-full.pdf').size,errors,chips},null,2));
  await page.getByRole('button',{name:/한국어/}).click();
  await page.getByRole('button',{name:/English/}).click();
  await page.locator('.result-overview h2').filter({hasText:'Your Saju at a glance'}).waitFor();
  await page.screenshot({path:'tmp/visual/result-english-mobile.png'});
  await page.locator('nav').first().getByRole('button').first().click();
  await page.getByRole('heading',{name:'Your story. A new perspective.'}).waitFor();
  await page.screenshot({path:'tmp/visual/home-english-mobile.png',fullPage:true});
  if(errors.length)throw new Error(errors.join('\n'));
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
